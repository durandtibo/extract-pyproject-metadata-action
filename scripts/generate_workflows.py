"""Generate ``nightly-test-stable.yaml`` from ``ci-test-local.yaml``.

The nightly workflow tests the latest release of the action with the same
steps as the local test, minus the jobs that test something added after
that release. Those jobs have a ``# local-only`` comment. ``uses:`` cannot
be an expression, so the stable workflow is a generated copy.

Usage: generate_workflows.py [--check]

Without ``--check``, writes the generated file. With ``--check``, exits
with 1 when the file on disk is not the generated one.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

WORKFLOWS_PATH = Path(__file__).resolve().parents[1] / ".github" / "workflows"
SOURCE_PATH = WORKFLOWS_PATH / "ci-test-local.yaml"
TARGET_PATH = WORKFLOWS_PATH / "nightly-test-stable.yaml"

# The latest release of the action: update it with every release (see the README).
STABLE_REF = "durandtibo/extract-pyproject-metadata-action@v0.2"

LOCAL_ONLY = "# local-only"
_JOB = re.compile(r"^  [A-Za-z0-9_-]+:\s*$")
_COMMENT = re.compile(r"^  #")


def split_jobs(lines: list[str]) -> tuple[list[str], list[list[str]]]:
    """Split a workflow into the lines before its jobs and one block of lines per job.

    The comment lines right before a job belong to that job.
    """
    start = lines.index("jobs:") + 1
    header, body = lines[:start], lines[start:]
    blocks: list[list[str]] = []
    current: list[str] = []
    pending_comments: list[str] = []
    for line in body:
        if _JOB.match(line):
            if current:
                blocks.append(current)
            current = [*pending_comments, line]
            pending_comments = []
        elif _COMMENT.match(line):
            # A comment at the job level (the comments of a job's steps are indented more).
            pending_comments.append(line)
        else:
            if pending_comments:
                current.extend(pending_comments)
                pending_comments = []
            current.append(line)
    if current:
        blocks.append(current)
    return header, blocks


def generate(source: str) -> str:
    """Return the content of the stable workflow generated from the local one."""
    lines = source.splitlines()
    header, blocks = split_jobs(lines)
    kept = [block for block in blocks if not any(line.strip() == LOCAL_ONLY for line in block)]
    text = "\n".join([*header, *(line for block in kept for line in block)]).rstrip() + "\n"
    text = text.replace("name: Test Local Action", "name: Test Stable Action", 1)
    text = re.sub(r"(?m)^(\s*(?:- )?uses:) \./$", rf"\1 {STABLE_REF}", text)
    banner = (
        "# Generated by scripts/generate_workflows.py from ci-test-local.yaml: do not edit.\n"
        "# Run `make workflows` after changing ci-test-local.yaml.\n"
    )
    return banner + text


def main(argv: list[str]) -> int:
    """Write the stable workflow, or check it with ``--check``."""
    generated = generate(SOURCE_PATH.read_text(encoding="utf-8"))
    if "--check" in argv:
        if TARGET_PATH.read_text(encoding="utf-8") != generated:
            print(f"::error::{TARGET_PATH.name} is out of date: run `make workflows`")
            return 1
        return 0
    TARGET_PATH.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
